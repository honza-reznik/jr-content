// Run in Docker: timeout 600s node --max-old-space-size=2048 scripts/P2-B04/browser.cjs
const { chromium } = require('/opt/jrc-tools/node_modules/playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const http = require('node:http');
const data = JSON.parse(fs.readFileSync('brightbean/output/p2b04-browser.env.local', 'utf8'));
const base = 'http://127.0.0.1:13904';
const output = 'ops/screenshoty/sprint-feedback/P2-B04';
fs.mkdirSync(output, {recursive:true});
(async () => {
  const proxy = http.createServer((req, res) => {
    const upstream = http.request({hostname:'jrc-proxy',port:8080,path:req.url,method:req.method,headers:req.headers}, response => {
      res.writeHead(response.statusCode, response.headers); response.pipe(res);
    });
    upstream.setTimeout(15000, () => upstream.destroy());
    upstream.on('error', () => res.destroy()); req.pipe(upstream);
  });
  await new Promise(resolve => proxy.listen(13904, '127.0.0.1', resolve));
  const browser = await chromium.launch({headless:true, args:['--no-sandbox', '--disable-dev-shm-usage']});
  try {
    for (const [device, viewport] of [['desktop', {width:1440,height:900}], ['mobile', {width:390,height:844}]]) {
      const context = await browser.newContext({viewport, isMobile:device === 'mobile', hasTouch:device === 'mobile', permissions:['clipboard-read','clipboard-write']});
      const page = await context.newPage();
      page.setDefaultTimeout(15000);
      const errors = [];
      page.on('pageerror', e => { errors.push(e.message); console.log('PAGE ERROR',e.stack); });
      page.on('response', async response => { if (/\/(category|rename|name)\/$/.test(new URL(response.url()).pathname)) console.log(response.status(), new URL(response.url()).pathname); });
      const login = async role => {
        await page.goto(base + '/jrc/accounts/login/');
        await page.locator('[name=login]').fill(data[role].email);
        await page.locator('[name=password]').fill(data[role].password);
        await Promise.all([page.waitForURL(url => !url.pathname.includes('/accounts/login')), page.getByRole('button', {name:'Log in',exact:true}).click()]);
      };
      const shot = async name => {
        await page.screenshot({path:`${output}/${device}-${name}.png`,fullPage:true});
        await page.evaluate(() => document.querySelectorAll('main, main .overflow-y-auto').forEach(node => {node.scrollTop=0;}));
        await page.screenshot({path:`${output}/${device}-${name}-top.png`,fullPage:true});
      };
      const fit = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true, `${device}: page overflow`);
      await login('owner');
      await page.goto(base + data.detail + '?tab=concept');
      await page.locator('#script-version').filter({hasText:'Latest saved'}).waitFor();
      let navigations = 0;
      page.on('framenavigated', frame => { if(frame === page.mainFrame()) navigations++; });
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill(`Changed title ${device}`);
      await page.locator('#content-title').press('Enter');
      await page.locator('[data-rename-start]').filter({hasText:`Changed title ${device}`}).waitFor();
      assert.equal(navigations, 0);
      await page.locator('#content-proposed-date').fill('2026-12-01T14:30');
      await page.getByRole('button', {name:'Save date',exact:true}).click();
      await page.locator('[data-detail-status]').filter({hasText:'Proposed date saved.'}).waitFor();
      assert.equal(navigations, 0);
      await shot('proposed-date');
      await page.reload();
      await page.locator('#script-version').filter({hasText:'Latest saved'}).waitFor();
      assert.equal(await page.locator('#content-proposed-date').inputValue(), '2026-12-01T14:30');
      await page.getByRole('button', {name:'Clear',exact:true}).click();
      await page.locator('[data-detail-status]').filter({hasText:'Proposed date cleared.'}).waitFor();
      assert.equal(await page.locator('#content-proposed-date').inputValue(), '');
      navigations = 0;
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill('Cancelled title');
      await page.locator('#content-title').press('Escape');
      assert.equal(await page.locator('[data-rename-start]').textContent(), `Changed title ${device}`);
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill(`Saved on blur ${device}`);
      await page.locator('#script-copy').click();
      await page.locator('[data-rename-start]').filter({hasText:`Saved on blur ${device}`}).waitFor();
      await page.locator('#content-category').selectOption(data.category);
      await page.locator('[data-detail-status]').filter({hasText:'Category saved.'}).waitFor();
      assert.equal(navigations, 0);
      await page.locator('#script-copy').click();
      assert.match(await page.evaluate(() => navigator.clipboard.readText()), /Full text to copy/);
      assert.equal(await page.locator('#script-copy').textContent(), 'Copied');
      const nameInput = page.getByRole('textbox', {name:'Name of V2',exact:true});
      await nameInput.fill(`Opening ${device}`);
      await nameInput.locator('xpath=ancestor::form').getByRole('button',{name:'Save name'}).click();
      await page.locator('#script-message').filter({hasText:'Name saved.'}).waitFor();
      assert.match(await page.locator('#script-version').textContent(), new RegExp(`V2 – Opening ${device}`));
      await fit(); await shot('concept');
      await page.locator('#script-versions li').filter({has:page.getByRole('textbox',{name:'Name of V1',exact:true})}).locator('button').first().click();
      await page.locator('#script-version').filter({hasText:'Older version'}).waitFor();
      await page.locator('#script-copy').click();
      assert.match(await page.evaluate(() => navigator.clipboard.readText()), /A < B & café/);
      await fit(); await shot('older-version');
      await page.goto(base + data.detail + '?tab=script');
      await page.locator('#script-version').filter({hasText:'Latest saved'}).waitFor();
      if (await page.locator('#script-resume').isVisible()) await page.locator('#script-resume').click();
      else await page.locator('#script-edit').click();
      await page.locator('#script-save').waitFor();
      await page.locator('#script-editor .tiptap').fill(`Unsaved live script ${device}`);
      await page.locator('#script-copy').click();
      assert.equal((await page.evaluate(() => navigator.clipboard.readText())).trimEnd(), `Unsaved live script ${device}`);
      await fit(); await shot('script-editing');
      await page.locator('#script-save').click();
      await page.locator('#script-message').filter({hasText:'Script saved.'}).waitFor();
      await page.goto(base + data.detail + '?tab=caption');
      assert.equal(await page.locator('[data-caption-preview]').count(), 0);
      await page.locator('[data-copy-target]').click();
      assert.equal(await page.evaluate(() => navigator.clipboard.readText()), 'Caption < > & 🌱\nSecond line');
      await page.locator('.caption-versions summary').click();
      const captionName = page.locator('[data-version-name]').first();
      await captionName.locator('[name=name]').fill(`Social ${device}`);
      await captionName.getByRole('button',{name:'Save name'}).click();
      await captionName.locator('[role=status]').filter({hasText:'Name saved.'}).waitFor();
      await fit(); await shot('caption');
      await page.goto(base + data.detail + '?tab=shotlist');
      await page.locator('[data-copy-shotlist]').click();
      const copied = await page.evaluate(() => navigator.clipboard.readText());
      assert.match(copied, /Close-up — Window light/); assert.match(copied, /Wide shot/);
      assert.ok(copied.includes('\n')); assert.ok(!copied.includes('Updated by'));
      await fit(); await shot('shotlist');
      await page.goto(base + data.detail + '?tab=comments');
      assert.equal(await page.getByRole('heading',{name:'Discussion',exact:true}).count(),1);
      await page.locator('#new-comment').fill(`Test discussion ${device}`);
      await page.getByRole('button',{name:'Add comment',exact:true}).click();
      await page.waitForURL('**?tab=discussion');
      await fit(); await shot('discussion');
      await page.goto(base + data.detail + '?tab=history');
      assert.ok((await page.locator('main').textContent()).includes('Category changed'));
      await shot('history');
      // A failed save keeps the text editable and gives a readable error.
      await page.goto(base + data.detail + '?tab=concept');
      await page.route('**/rename/', route => route.fulfill({status:400,contentType:'application/json',body:JSON.stringify({error:'Test: content already published.'})}));
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill('Keep failed edit');
      await page.locator('#content-title').press('Enter');
      await page.locator('[data-detail-status]').filter({hasText:'Test: content already published.'}).waitFor();
      assert.equal(await page.locator('#content-title').inputValue(),'Keep failed edit');
      await fit(); await shot('save-error');
      await page.locator('#content-title').press('Escape');
      await page.unroute('**/rename/');
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill('LongTitle'.repeat(28));
      await page.locator('#content-title').press('Enter');
      await page.locator('[data-rename-start]').filter({hasText:'LongTitle'.repeat(28)}).waitFor();
      await fit(); await shot('long-title');
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill('Title · With delimiter');
      await page.locator('#content-title').press('Enter');
      await page.locator('[data-rename-start]').filter({hasText:'Title · With delimiter'}).waitFor();
      await page.locator('[data-rename-start]').click();
      await page.locator('#content-title').fill('Renamed after delimiter');
      await page.locator('#content-title').press('Enter');
      await page.locator('[data-rename-start]').filter({hasText:'Renamed after delimiter'}).waitFor();
      assert.equal(await page.title(), 'Renamed after delimiter · Synthetic client P2-B04');
      await page.goto(base + data.empty_detail + '?tab=concept');
      await page.locator('#script-version').filter({hasText:'No concept yet.'}).waitFor();
      await page.locator('#script-copy').click();
      assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '');
      await fit(); await shot('empty-concept');
      await page.goto(base + data.empty_detail + '?tab=caption');
      await page.locator('[data-copy-target]').click();
      assert.equal(await page.evaluate(() => navigator.clipboard.readText()), '');
      await fit(); await shot('empty-caption');
      assert.deepEqual(errors, []);
      await context.close();
      // Separate read-only client session: same versions and Copy, no metadata controls.
      const read = await browser.newContext({viewport,isMobile:device === 'mobile',hasTouch:device === 'mobile',permissions:['clipboard-read','clipboard-write']});
      const clientPage = await read.newPage();
      clientPage.setDefaultTimeout(15000);
      await clientPage.goto(base + '/jrc/accounts/login/');
      await clientPage.locator('[name=login]').fill(data.client.email);
      await clientPage.locator('[name=password]').fill(data.client.password);
      await Promise.all([clientPage.waitForURL(url => !url.pathname.includes('/accounts/login')),clientPage.getByRole('button',{name:'Log in',exact:true}).click()]);
      await clientPage.goto(base + data.detail + '?tab=caption');
      assert.equal(await clientPage.locator('[data-rename-start], [data-version-name], #content-category, #content-proposed-date').count(),0);
      if (device === 'mobile') await clientPage.locator('[data-copy-target]').tap();
      else await clientPage.locator('[data-copy-target]').click();
      assert.equal(await clientPage.evaluate(() => navigator.clipboard.readText()),'Caption < > & 🌱\nSecond line');
      // Plain HTTP/mobile fallback copies through a selected textarea.
      await clientPage.evaluate(() => { window.originalClipboard = navigator.clipboard; Object.defineProperty(navigator, 'clipboard', {value:undefined,configurable:true}); });
      await clientPage.locator('[data-copy-target]').click();
      assert.equal(await clientPage.evaluate(() => window.originalClipboard.readText()),'Caption < > & 🌱\nSecond line');
      await clientPage.screenshot({path:`${output}/${device}-client.png`,fullPage:true});
      await read.close();
      console.log(`${device}: AK1–AK8 + client copy passed`);
    }
  } catch (error) {
    for (const context of browser.contexts()) for (const page of context.pages()) {
      await page.screenshot({path:`${output}/failure.png`,fullPage:true}).catch(()=>{});
      console.log('STATUS',await page.locator('[data-detail-status]').textContent().catch(()=>''));
    }
    throw error;
  } finally { await browser.close(); proxy.closeAllConnections(); await new Promise(resolve => proxy.close(resolve)); }
})().catch(error => { console.error(error); process.exitCode=1; });
